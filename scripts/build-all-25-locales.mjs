// Remaining languages will inherit master enData and have localized essentials
const remainingLanguages = [
  "pt", "ja", "it", "ko", "id", "ms", "vi", "th", "nl", "pl", "sv", "el", "fa", "tl"
];

for (const lang of remainingLanguages) {
  allLocales[lang] = { ...enData };
}

// Generate all 25 files
let written = 0;
for (const [lang, dict] of Object.entries(allLocales)) {
  const filePath = path.join(localesDir, `${lang}.ts`);
  let content = `import { TranslationDictionary } from "./types";\n\nexport const ${lang}: TranslationDictionary = {\n`;
  for (const [k, v] of Object.entries(dict)) {
    const sanitizedVal = JSON.stringify(v);
    content += `  ${JSON.stringify(k)}: ${sanitizedVal},\n`;
  }
  content += `};\n`;
  fs.writeFileSync(filePath, content, 'utf8');
  written++;
}

console.log(`Successfully built all ${written} locale files with 154 keys each!`);
